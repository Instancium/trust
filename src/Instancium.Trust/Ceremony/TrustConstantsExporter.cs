namespace Instancium.Trust.Ceremony;

using Instancium.Trust.Keys;
using System.Globalization;
using System.Text;

/// <summary>
/// Generates compiled trust anchors from the same key set as DNS and GitHub exports,
/// guaranteeing 100% fingerprint consistency across all out-of-band channels.
/// </summary>
public static class TrustConstantsExporter
{
    public static string Export(RootPublicKeyDocument primary, RootPublicKeyDocument backup)
    {
        ArgumentNullException.ThrowIfNull(primary);
        ArgumentNullException.ThrowIfNull(backup);

        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated>");
        builder.AppendLine("// Generated by Instancium.Trust key ceremony. Do not edit manually.");
        builder.AppendLine("// </auto-generated>");
        builder.AppendLine("namespace Instancium.Trust.Generated;");
        builder.AppendLine();
        builder.AppendLine("/// <summary>Out-of-band trust anchors compiled into verification clients.</summary>");
        builder.AppendLine("public static class TrustConstants");
        builder.AppendLine("{");
        builder.AppendLine("    public const string DnsTrustRecordName = \"_trust.instancium.com\";");
        builder.AppendLine(CultureInfo.InvariantCulture, $"    public const string SignatureAlgorithm = \"{primary.Alg}\";");
        builder.AppendLine(CultureInfo.InvariantCulture, $"    public const string PrimaryRootKid = \"{primary.Kid}\";");
        builder.AppendLine(CultureInfo.InvariantCulture, $"    public const string PrimaryRootPublicKey = \"{primary.PublicKey}\";");
        builder.AppendLine(CultureInfo.InvariantCulture, $"    public const string PrimaryRootSha256 = \"{primary.Sha256}\";");
        builder.AppendLine(CultureInfo.InvariantCulture, $"    public const string BackupRootKid = \"{backup.Kid}\";");
        builder.AppendLine(CultureInfo.InvariantCulture, $"    public const string BackupRootPublicKey = \"{backup.PublicKey}\";");
        builder.AppendLine(CultureInfo.InvariantCulture, $"    public const string BackupRootSha256 = \"{backup.Sha256}\";");
        builder.AppendLine("}");
        return builder.ToString();
    }
}
